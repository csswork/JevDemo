/**
 * 每个模型一套人设（输入层 DeepSeek 的 system prompt）。
 *
 * 人设是照着模型的**外形**定的 —— 用户看得见她长什么样，性格和说话方式要对得上：
 * 穿制服、黑长直的不该一开口就是辣妹腔，穿围裙的像是店里的人。
 * 外形描述来自 `__faces` 对比图（dev-out/model_comparison*.jpg），也写进 prompt，
 * 用户问起"你的头发""你的衣服"时她知道自己长什么样。
 *
 * 这里只写**人格和说话方式**。表情、动作、视线由 Jev 判断，写在这里不会生效；
 * 通用规则（口语、短句、只输出台词）在 server/persona.md。
 *
 * id 和 src/models.ts 的模型 id 一一对应，也是聊天记录的 session id。
 * 这个文件在 vite.config 的引用链上，改完 dev server 会自动重启。
 */

export interface Persona {
  id: string;
  name: string;
  /** 外形（照着模型写的） */
  look: string;
  /** 身份 / 背景 */
  identity: string;
  /** 性格 */
  traits: string[];
  /** 说话方式 */
  speech: string[];
  likes: string[];
  dislikes: string[];
  /** 和用户的关系 */
  relation: string;
  /** 第一次见面（或重置之后）的开场白，不花钱，直接用 */
  greeting: string;
  /** 语气示例：只让模型抓语感，prompt 里写明不要照抄 */
  examples: string[];
}

