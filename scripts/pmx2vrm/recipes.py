def resolve(available, overrides=None):
    """available：模型里有的变形名。返回 {形状键: 配方}、{形状键: 选了第几个备选}、缺的形状"""
    out, picked, missing = {}, {}, []
    alt = dict(ALT)
    for k, v in (overrides or {}).items():
        alt[k] = [v] + alt.get(k, [])
    for key, options in alt.items():
        for i, mix in enumerate(options):
            if all(n in available for n, _ in mix):
                out[key] = mix
                picked[key] = '+'.join(f'{n}×{w:g}' if w != 1 else n for n, w in mix)
                break
        else:
            missing.append(key)
    return out, picked, missing
